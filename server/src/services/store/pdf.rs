/// Writes the imported document row and its pages in one transaction. `doc_id`
/// is generated by the caller (it names the stored source file too).
#[allow(clippy::too_many_arguments)]
pub async fn import_document(
    db: &DbPool,
    doc_id: Uuid,
    owner: Uuid,
    title: &str,
    source_path: &str,
    page_count: i32,
    source_file_id: Option<Uuid>,
    pages_meta: &[(f64, f64)],
) -> Result<Vec<Uuid>> {
    let mut tx = db.begin().await?;
    tx.execute(
        "INSERT INTO paintsharp.pdf_documents
            (id, owner_id, title, source_path, page_count, source_file_id)
         VALUES ($1, $2, $3, $4, $5, $6)",
        params![doc_id, owner, title, source_path, page_count, source_file_id],
    )
    .await?;

    let mut page_ids = Vec::with_capacity(pages_meta.len());
    for (n, (w, h)) in pages_meta.iter().enumerate() {
        let page_id = new_id();
        tx.execute(
            "INSERT INTO paintsharp.pdf_pages (id, document_id, page_number, width, height, source_index)
             VALUES ($1, $2, $3, $4, $5, $6)",
            params![page_id, doc_id, (n + 1) as i32, *w, *h, n as i32],
        )
        .await?;
        page_ids.push(page_id);
    }
    tx.commit().await?;
    Ok(page_ids)
}

