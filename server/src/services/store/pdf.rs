/// Deletes a trashed document and returns `(source_path, file_id)`.
/// `Ok(None)` means no trashed document matched.
pub async fn delete_document(
    db: &DbPool,
    id: Uuid,
    owner: Uuid,
) -> Result<Option<(Option<String>, Option<Uuid>)>> {
    let del = "DELETE FROM paintsharp.pdf_documents
               WHERE id = $1 AND owner_id = $2 AND is_trashed = TRUE";
    let sel = "SELECT source_path, file_id FROM paintsharp.pdf_documents
               WHERE id = $1 AND owner_id = $2 AND is_trashed = TRUE";
    let mut tx = db.begin().await?;
    let row = kubuno_db::returning::delete_returning_row(
        &mut tx,
        del,
        params![id, owner],
        "source_path, file_id",
        sel,
        params![id, owner],
    )
    .await?;
    let out = match row {
        Some(r) => Some((r.try_get::<Option<String>>("source_path")?, r.try_get::<Option<Uuid>>("file_id")?)),
        None => None,
    };
    tx.commit().await?;
    Ok(out)
}

/// `source_path` + `title`, for serving the imported source PDF.
pub async fn source_of(db: &DbPool, id: Uuid, owner: Uuid) -> Result<Option<(Option<String>, String)>> {
    let row = db
        .fetch_optional_row(
            "SELECT source_path, title FROM paintsharp.pdf_documents
             WHERE id = $1 AND owner_id = $2",
            params![id, owner],
        )
        .await?;
    match row {
        Some(r) => Ok(Some((r.try_get::<Option<String>>("source_path")?, r.try_get::<String>("title")?))),
        None => Ok(None),
    }
}

