/// Inserts a page after `after`, shifting the later pages and bumping the
/// document's page count. Returns `(page_id, new_page_number)`.
pub async fn add_page(
    db: &DbPool,
    doc_id: Uuid,
    owner: Uuid,
    after: i32,
    width: f64,
    height: f64,
) -> Result<(Uuid, i32)> {
    let mut tx = db.begin().await?;
    tx.execute(
        "UPDATE paintsharp.pdf_pages SET page_number = page_number + 1
         WHERE document_id = $1 AND page_number > $2",
        params![doc_id, after],
    )
    .await?;

    let new_num = after + 1;
    let page_id = new_id();
    tx.execute(
        "INSERT INTO paintsharp.pdf_pages (id, document_id, page_number, width, height)
         VALUES ($1, $2, $3, $4, $5)",
        params![page_id, doc_id, new_num, width, height],
    )
    .await?;

    tx.execute(
        "UPDATE paintsharp.pdf_documents SET page_count = page_count + 1, last_edited_by = $1
         WHERE id = $2",
        params![owner, doc_id],
    )
    .await?;

    tx.commit().await?;
    Ok((page_id, new_num))
}

/// Deletes the given page, closes the gap in numbering and decrements the
/// document's page count. Returns the deleted page's id (if it existed).
pub async fn delete_page(db: &DbPool, doc_id: Uuid, owner: Uuid, page_num: i32) -> Result<Option<Uuid>> {
    let mut tx = db.begin().await?;
    let deleted_id: Option<Uuid> = tx
        .fetch_optional_scalar::<Uuid>(
            "SELECT id FROM paintsharp.pdf_pages WHERE document_id = $1 AND page_number = $2",
            params![doc_id, page_num],
        )
        .await?;
    tx.execute(
        "DELETE FROM paintsharp.pdf_pages WHERE document_id = $1 AND page_number = $2",
        params![doc_id, page_num],
    )
    .await?;
    tx.execute(
        "UPDATE paintsharp.pdf_pages SET page_number = page_number - 1
         WHERE document_id = $1 AND page_number > $2",
        params![doc_id, page_num],
    )
    .await?;
    tx.execute(
        "UPDATE paintsharp.pdf_documents SET page_count = page_count - 1, last_edited_by = $1
         WHERE id = $2",
        params![owner, doc_id],
    )
    .await?;
    tx.commit().await?;
    Ok(deleted_id)
}

/// Reorders pages. `order[new_pos]` is the old (1-based) page number that should
/// land at `new_pos + 1`. Two passes through negative temporaries avoid the
/// UNIQUE(document_id, page_number) conflict.
pub async fn reorder_pages(db: &DbPool, doc_id: Uuid, order: &[i32]) -> Result<()> {
    let mut tx = db.begin().await?;
    for (new_pos, &old_num) in order.iter().enumerate() {
        let tmp = -(new_pos as i32 + 1);
        tx.execute(
            "UPDATE paintsharp.pdf_pages SET page_number = $1
             WHERE document_id = $2 AND page_number = $3",
            params![tmp, doc_id, old_num],
        )
        .await?;
    }
    for new_pos in 0..order.len() {
        let tmp = -(new_pos as i32 + 1);
        tx.execute(
            "UPDATE paintsharp.pdf_pages SET page_number = $1
             WHERE document_id = $2 AND page_number = $3",
            params![(new_pos + 1) as i32, doc_id, tmp],
        )
        .await?;
    }
    tx.commit().await?;
    Ok(())
}

