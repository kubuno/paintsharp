// ── Documents ─────────────────────────────────────────────────────────────────

pub async fn list_documents(
    db: &DbPool,
    owner: Uuid,
    starred: bool,
    trashed: bool,
    limit: i64,
    offset: i64,
) -> Result<Vec<PdfDocumentSummary>> {
    let sql = if starred {
        format!(
            "SELECT {SUMMARY_COLS} FROM paintsharp.pdf_documents
             WHERE owner_id = $1 AND is_starred = TRUE AND is_trashed = FALSE
             ORDER BY updated_at DESC LIMIT $2 OFFSET $3"
        )
    } else if trashed {
        format!(
            "SELECT {SUMMARY_COLS} FROM paintsharp.pdf_documents
             WHERE owner_id = $1 AND is_trashed = TRUE
             ORDER BY trashed_at DESC LIMIT $2 OFFSET $3"
        )
    } else {
        format!(
            "SELECT {SUMMARY_COLS} FROM paintsharp.pdf_documents
             WHERE owner_id = $1 AND is_trashed = FALSE
             ORDER BY updated_at DESC LIMIT $2 OFFSET $3"
        )
    };
    Ok(db.fetch_all_as::<PdfDocumentSummary>(&sql, params![owner, limit, offset]).await?)
}

/// Creates a document plus `page_count` blank pages atomically. Returns
/// `(doc_id, page_ids)`, the page ids ordered from page 1.
pub async fn create_document(
    db: &DbPool,
    owner: Uuid,
    title: &str,
    page_count: i32,
    width: f64,
    height: f64,
) -> Result<(Uuid, Vec<Uuid>)> {
    let doc_id = new_id();
    let mut tx = db.begin().await?;
    tx.execute(
        "INSERT INTO paintsharp.pdf_documents (id, owner_id, title, page_count)
         VALUES ($1, $2, $3, $4)",
        params![doc_id, owner, title, page_count],
    )
    .await?;
    let mut page_ids = Vec::with_capacity(page_count.max(0) as usize);
    for n in 1..=page_count {
        let page_id = new_id();
        tx.execute(
            "INSERT INTO paintsharp.pdf_pages (id, document_id, page_number, width, height)
             VALUES ($1, $2, $3, $4, $5)",
            params![page_id, doc_id, n, width, height],
        )
        .await?;
        page_ids.push(page_id);
    }
    tx.commit().await?;
    Ok((doc_id, page_ids))
}

