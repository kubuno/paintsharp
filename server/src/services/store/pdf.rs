pub async fn update_document(
    db: &DbPool,
    id: Uuid,
    owner: Uuid,
    title: Option<&str>,
    thumbnail_path: Option<&str>,
    is_starred: Option<bool>,
    settings: Option<&Value>,
) -> Result<u64> {
    Ok(db
        .execute(
            "UPDATE paintsharp.pdf_documents SET
                title          = COALESCE($1, title),
                thumbnail_path = COALESCE($2, thumbnail_path),
                is_starred     = COALESCE($3, is_starred),
                settings       = COALESCE($4, settings),
                last_edited_by = $5
             WHERE id = $6 AND owner_id = $7",
            params![
                title,
                thumbnail_path,
                is_starred,
                settings.cloned(),
                owner,
                id,
                owner
            ],
        )
        .await?)
}

pub async fn exists(db: &DbPool, id: Uuid, owner: Uuid) -> Result<bool> {
    Ok(db
        .fetch_optional_scalar::<Uuid>(
            "SELECT id FROM paintsharp.pdf_documents WHERE id = $1 AND owner_id = $2 LIMIT 1",
            params![id, owner],
        )
        .await?
        .is_some())
}

/// Whether a live (non-trashed) document is owned by `owner`.
pub async fn check_owner(db: &DbPool, id: Uuid, owner: Uuid) -> Result<bool> {
    Ok(db
        .fetch_optional_scalar::<Uuid>(
            "SELECT id FROM paintsharp.pdf_documents
             WHERE id = $1 AND owner_id = $2 AND is_trashed = FALSE LIMIT 1",
            params![id, owner],
        )
        .await?
        .is_some())
}

pub async fn doc_file_id(db: &DbPool, id: Uuid, owner: Uuid) -> Result<Uuid> {
    let fid: Option<Uuid> = db
        .fetch_optional_scalar::<Uuid>(
            "SELECT file_id FROM paintsharp.pdf_documents WHERE id = $1 AND owner_id = $2",
            params![id, owner],
        )
        .await?;
    if let Some(f) = fid {
        return Ok(f);
    }
    if exists(db, id, owner).await? {
        Err(PaintsharpError::NotFound(format!("Contenu du document {id}")))
    } else {
        Err(PaintsharpError::NotFound(id.to_string()))
    }
}

